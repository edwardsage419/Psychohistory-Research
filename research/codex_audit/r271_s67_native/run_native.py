#!/usr/bin/env python3
"""Replay pinned original CLIs and independent DP without changing originals.

python -B research/codex_audit/r271_s67_native/run_native.py . --output /tmp/s67-audit
Use a distinct output directory per concurrent run.
"""
import argparse
import hashlib
import json
from pathlib import Path
import platform
import shutil
import subprocess
import sys
import tempfile
from oracle import verify_results

R='research/validation/r271_s67_overlapping_families_20261030.js'
B='research/evidence_audit/b_r271_s67_independent_inclusion_exclusion_20261030.js'
CSV='R271_S67_ALL_13584_OVERLAPPING_NULL_SOURCE_ROWS.csv'
JSON='R271_S67_EXACT_FAMILYWISE_RISKS.json'
RECEIPT='R271_S67_MACHINE_RECEIPT.json'
PINS={R:'f38992f2bdca575094bc08f28c443d8c4d86e1cf',B:'ccec09f9feda72f5b564b4d27337d178da429979',
      'research/validation/'+CSV:'4bfed50d9df756d537d239868771181e07a2c216',
      'research/validation/'+JSON:'6b56bd2b82790e531a938106db5eada7da416a18',
      'research/validation/'+RECEIPT:'3fb736ad2273408f3dd127e932b239ff06d36915'}

def require(ok,message):
    if not ok:raise ValueError(message)

def identity(root):
    result={}
    for path,pin in PINS.items():
        raw=(root/path).read_bytes();blob=hashlib.sha1(b'blob '+str(len(raw)).encode()+b'\0'+raw).hexdigest()
        require(blob==pin,'source identity '+path)
        result[path]={'git_blob':blob,'bytes':len(raw),'sha256':hashlib.sha256(raw).hexdigest()}
    return result

def main():
    p=argparse.ArgumentParser();p.add_argument('root',type=Path);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
    root,out=a.root.resolve(),a.output.resolve()
    # Protect all source files from log-path collisions before any output mutation.
    targets=[out/'execution.json']+[out/(label+suffix) for label in ('r_generator','b_persisted','b_regenerated','negative_risk','negative_csv','metadata_freeze') for suffix in ('.stdout','.stderr')]
    protected=[root/path for path in PINS]+[Path(__file__).resolve(),Path(__file__).with_name('oracle.py').resolve()]
    require(not any(t==s.resolve() or (t.exists() and s.exists() and t.samefile(s)) for t in targets for s in protected),'output aliases input')
    out.mkdir(parents=True,exist_ok=True);(out/'execution.json').unlink(missing_ok=True)
    before=identity(root);archive=root/'research/validation';commands=[]
    def run(label,cmd,expected_zero=True):
        r=subprocess.run(cmd,cwd=root,capture_output=True,text=True,timeout=60)
        (out/(label+'.stdout')).write_text(r.stdout);(out/(label+'.stderr')).write_text(r.stderr)
        commands.append({'label':label,'command':cmd,'cwd':str(root),'exit_code':r.returncode,'stdout':label+'.stdout','stderr':label+'.stderr'})
        require((r.returncode==0)==expected_zero,'unexpected CLI acceptance/rejection '+label)
        return json.loads(r.stdout) if r.returncode==0 else None
    persisted=run('b_persisted',['node',str(root/B),str(archive)])
    require(persisted.get('status')=='PASS' and persisted.get('source_rows')==13584 and persisted.get('worlds')==27 and persisted.get('mutations_rejected')==6,'B persisted coverage')
    oracle_result=verify_results(json.loads((archive/JSON).read_text()))
    with tempfile.TemporaryDirectory(prefix='s67-native-') as temp:
        temp=Path(temp);generated=temp/'generated'
        r=run('r_generator',['node',str(root/R),str(generated)])
        require(r==json.loads((archive/RECEIPT).read_text()),'generator stdout receipt')
        equalities=[]
        for name in (CSV,JSON,RECEIPT):
            raw=(generated/name).read_bytes();require(raw==(archive/name).read_bytes(),'regenerated bytes '+name)
            equalities.append({'file':name,'byte_equal':True,'bytes':len(raw),'sha256':hashlib.sha256(raw).hexdigest()})
        regenerated=run('b_regenerated',['node',str(root/B),str(generated)])
        require(regenerated==persisted,'B regenerated output differs')
        controls=[]
        for label in ('negative_risk','negative_csv','metadata_freeze'):
            dest=temp/label;dest.mkdir()
            for name in (CSV,JSON,RECEIPT):shutil.copyfile(archive/name,dest/name)
            obj=json.loads((dest/JSON).read_text())
            if label=='negative_risk':obj['worlds'][0]['exact_familywise_false_positive_risk']='999'
            elif label=='negative_csv':
                lines=(dest/CSV).read_text().splitlines(keepends=True);del lines[1];(dest/CSV).write_text(''.join(lines))
            else:obj['R073']='MODIFIED'
            (dest/JSON).write_text(json.dumps(obj,indent=2)+'\n')
            receipt=json.loads((dest/RECEIPT).read_text())
            receipt['source_sha256']=hashlib.sha256((dest/CSV).read_bytes()).hexdigest()
            receipt['results_sha256']=hashlib.sha256((dest/JSON).read_bytes()).hexdigest()
            (dest/RECEIPT).write_text(json.dumps(receipt,indent=2)+'\n')
            b_result=run(label,['node',str(root/B),str(dest)],expected_zero=label=='metadata_freeze')
            if label!='negative_csv':
                try:verify_results(obj)
                except ValueError:oracle_reject=True
                else:oracle_reject=False
                require(oracle_reject,'oracle mutation false acceptance '+label)
            else:oracle_reject='NOT_APPLICABLE; oracle does not read CSV'
            controls.append({'case':label,'B_accepted':b_result is not None,'oracle_rejected':oracle_reject,'checksums_recomputed':True})
    require(before==identity(root),'original source changed during replay')
    result={'status':'COMPLETE','pinned_source_baseline':'e2614fec5027247de328a5aeef295c4ed3bc9338',
            'python':sys.version,'node':subprocess.check_output(['node','--version'],text=True).strip(),'platform':platform.platform(),
            'seed':'N/A; exact finite computation','source_identity':before,'source_unchanged':True,
            'original_positive_clis':3,'original_negative_cli_rejections':2,'metadata_counterexample_acceptances':1,
            'B_persisted_result':persisted,'regenerated_byte_comparisons':equalities,'oracle':oracle_result,
            'controls':controls,'commands':commands,'evidence':'NONBLIND_INTERNAL_ARTIFICIAL_E1',
            'strict_blind_prescore_freeze':False,'new_E2':0,'new_E3':0,'external_team_replications':0,
            'full_repo_tests':'NOT_RUN','historical_unarchived_python_tests':'NOT_RUN','ci':'NOT_RUN',
            'code_sha256':{name:hashlib.sha256(Path(__file__).with_name(name).read_bytes()).hexdigest() for name in ('run_native.py','oracle.py')}}
    with tempfile.NamedTemporaryFile(mode='w',encoding='utf-8',dir=out,delete=False) as f:
        staged=Path(f.name);f.write(json.dumps(result,indent=2)+'\n')
    staged.replace(out/'execution.json')
    print(json.dumps({'status':'COMPLETE','original_positive_clis':3,'worlds':27,'rows':13584,'regenerated_files_byte_equal':3,'metadata_gap_reproduced':True}))

if __name__=='__main__':main()
