"""R106 D pure synthetic source-like 26-session, 260-human, 3620-row dyadic model tests.

No source real behavioral records. All synthetic labels and choices generated here.
"""
from __future__ import annotations
import copy
import unittest

import r106_phase_d_2025_new_UK_26sessions_own_partner_equal_shrink_brier as d


def fixture(mode="partner",rematch=False):
    rows=[]
    # 24 lab sessions with 14 periods and 2 with 13: 3620 actor rows.
    for sid in range(1,27):
        periods=13 if sid>24 else 14
        prior={}
        for t in range(1,periods+1):
            current={}
            for p in range(1,11):
                partner=p+1 if p%2 else p-1
                if mode=="partner":
                    # Target generated by partner's last observed true choice.
                    act=((p+sid)%2) if t==1 else prior[partner]
                elif mode=="self":
                    act=(p+sid)%2
                else:
                    act=(p+sid+t)%2
                current[p]=act
            for p in range(1,11):
                partner=p+1 if p%2 else p-1
                group=(p+1)//2
                if rematch and sid==1 and t==5:
                    # Pair identity at t5 is different; leave explicit group
                    # keyed same but will be seen only as rematched at source.
                    group=6-group
                rows.append({
                    "s":sid,"p":p,"g":group,"t":t,"part":2,"game":1,
                    "k":t,"a":current[p],
                    "reported_peer":current[partner],
                    "reported_previous_peer":None if t==1 else prior[partner],
                })
            prior=current
    assert len(rows)==3620
    return rows


class D106FrozenOwnPartnerControls(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.base=fixture("partner")
        cls.tested=d.evaluate(cls.base,enforce_real_universe=True)

    def test_true_26_session_and_260_people_source(self):
        result=self.tested
        self.assertEqual(result["source_true_original_lab_sessions"],26)
        self.assertEqual(result["source_true_distinct_session_persons"],260)
        self.assertEqual(result["source_original_pair_rounds"],1810)
        self.assertEqual(result["source_all_stage2_original_person_round_rows"],3620)
        self.assertGreaterEqual(result["source_all_eligible_target_count"],800)

    def test_dyadic_history_four_controls_same_targets(self):
        x=self.tested
        self.assertEqual(set(x["overall_all_eligible"]["MSE"]),set(d.MODELS))
        self.assertEqual(len(x["anonymous_original_lab_session_results"]),26)
        self.assertEqual(sum(z["all_recorded"]["target_count"] for z in x["anonymous_original_lab_session_results"]),x["overall_all_eligible"]["target_count"])
        self.assertEqual(x["source_sessions_with_at_least_one_eligible_target"],26)

    def test_true_partner_lag_improves_in_synthetic_partner_generating_world(self):
        x=self.tested
        self.assertGreater(x["overall_all_eligible"]["gains"]["M3_vs_M2_peer_specific"],0)
        self.assertGreater(x["overall_all_eligible"]["gains"]["M3_vs_M4_donor_sham"],0)

    def test_negative_competitor_possible_on_synthetic_self_only_world(self):
        x=d.evaluate(fixture("self"),enforce_real_universe=True)
        self.assertEqual(x["overall_all_eligible"]["MSE"]["M1"],0)
        self.assertGreater(x["overall_all_eligible"]["MSE"]["M3"],0)
        self.assertLess(x["overall_all_eligible"]["gains"]["M3_vs_M1_own_only"],0)

    def test_fixed_windows_cover_same_targets(self):
        x=self.tested
        self.assertEqual(x["early_practiceperiod_k2_to_k3"]["target_count"]+x["late_practiceperiod_k4_plus"]["target_count"],x["source_all_eligible_target_count"])

    def test_earliest_lagged_period_not_scored(self):
        x=self.tested
        self.assertEqual(x["source_frozen_excluded_target_counts"]["first_stage_period"],260)
        self.assertEqual(x["source_all_eligible_target_count"],3360)

    def test_current_source_peer_reciprocity_failure(self):
        bad=copy.deepcopy(self.base)
        bad[1]["reported_peer"]=1-bad[1]["reported_peer"]
        self.assertRaisesRegex(d.SourceError,"R106_D_ORIGINAL_CURRENT_COUNTERPART",d.evaluate,bad)

    def test_previous_source_partner_history_failure(self):
        bad=copy.deepcopy(self.base)
        target=next(i for i,r in enumerate(bad) if r["s"]==1 and r["p"]==1 and r["t"]==2)
        bad[target]["reported_previous_peer"]=1-bad[target]["reported_previous_peer"]
        self.assertRaisesRegex(d.SourceError,"R106_D_AUTHOR_PREVIOUS_COUNTERPART",d.evaluate,bad)

    def test_one_rematch_boundary_counts_without_future_peer_membership(self):
        # Move both partners of one group to a different group label t5
        # while preserving complete 2-person current source pairs.
        bad=copy.deepcopy(self.base)
        for r in bad:
            if r["s"]==1 and r["t"]==5 and r["g"] in (1,2):
                r["g"]=3-r["g"]
        x=d.evaluate(bad)
        self.assertGreater(x["source_frozen_excluded_target_counts"]["rematch_or_noncontiguous_previous_source_pair"],0)
        self.assertLess(x["source_all_eligible_target_count"],3360)

    def test_two_peer_group_missing_or_duplicate_actor_fails(self):
        bad=copy.deepcopy(self.base)
        bad[0]["p"]=bad[1]["p"]
        self.assertRaises(d.SourceError,d.evaluate,bad)

    def test_nonbinary_source_action_rejected(self):
        self.assertRaises(d.SourceError,d.binary,2)
        self.assertRaises(d.SourceError,d.binary,float("nan"))
        self.assertIsNone(d.optional_binary,float("nan"))

    def test_fixed_laplace_formula(self):
        self.assertEqual(d.estimate(0,0),0.5)
        self.assertEqual(d.estimate(1,2),0.5)
        self.assertEqual(d.estimate(4,4),5/6)

    def test_no_private_human_row_export_or_caused_psychology_claim(self):
        x=self.tested
        self.assertFalse(x["original_human_ID_or_action_rows_exported"])
        self.assertTrue(x["not_R073_exact_frozen_dyadic_score_protocol"])
        self.assertTrue(x["not_calendar_prospective"])
        self.assertTrue(x["not_causal_opponent_social_learning"])

if __name__=="__main__":
    unittest.main()
