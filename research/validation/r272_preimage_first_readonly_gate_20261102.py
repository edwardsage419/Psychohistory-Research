#!/usr/bin/env python3
"""Read-only R272 preimage-first audit and isolated regeneration candidate.

This is a local candidate. It does not change the archived workflow, freeze,
source or historical results. Requires the extracted independent R272 checker.
"""
import argparse
import hashlib
import importlib.util
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

GATE_SHA256 = 'f7109f8f815d166128ca3429fb42ff3e7cac780d03fb78f8243aeabbd6fbb786'
ORIGINAL_BLOB = '13843eecf2f9f05c19ee5545bdb224f58313f367'
FREEZE_BLOB = '9fbdb0078a58c4a9c0a548643227e30da5731119'
RECEIPT_BLOB = '85d36858911a7eb79c73c607cddf45ea88852a60'
ORIGINAL = 'research/R272/r272_exact_train_test_prediction.py'
FREEZE = 'protocols/R272_OUT_OF_SAMPLE_9_BERNOULLI_WORLDS_576_FULL_SOURCE_PRESCORE_FREEZE_2026-10-23.md'
ARCHIVES = (
    'research/R272/R272_ALL_576_ORIGINAL_TRAIN_AND_TEST_SOURCES.csv',
    'research/R272/R272_EXACT_RESULTS.json',
    'research/R272/R272_MACHINE_RECEIPT.json',
)


def require(condition, message):
    if not condition:
        raise ValueError(message)


def blob(data):
    return hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest()


def sha(data):
    return hashlib.sha256(data).hexdigest()


def read(root, relative):
    path = root / relative
    require(path.is_file() and not path.is_symlink(), 'missing or linked input: ' + relative)
    return path.read_bytes()


def load_gate(path):
    raw = path.read_bytes()
    require(sha(raw) == GATE_SHA256, 'independent checker source identity differs')
    spec = importlib.util.spec_from_file_location('r272_pinned_gate', path)
    require(spec is not None and spec.loader is not None, 'cannot load checker')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def verify_preimage(root, gate):
    original = read(root, ORIGINAL)
    freeze = read(root, FREEZE)
    require(blob(original) == ORIGINAL_BLOB, 'original generator Git blob differs')
    require(blob(freeze) == FREEZE_BLOB, 'prescore freeze Git blob differs')
    cb, rb, mb = (read(root, p) for p in ARCHIVES)
    # The archived candidate pins CSV and results bytes but does not pin the
    # original receipt's exact byte identity. This extra guard closes that gap.
    require(blob(mb) == RECEIPT_BLOB, 'archived machine receipt Git blob differs')
    scientific = gate.verify(cb, rb, mb, pins=True)
    require(scientific['status'] == 'PASS', 'independent scientific verification failed')
    return (original, freeze, cb, rb, mb), scientific


def run_checked(argv, cwd):
    process = subprocess.run(argv, cwd=cwd, capture_output=True, text=True,
                             timeout=120, check=False)
    require(process.returncode == 0,
            'native process rejected: ' + repr(argv) + '\n' + process.stderr[-2000:])
    return process.stdout.strip()


def native_gate_cli(gate_path, root):
    command = [sys.executable]
    if sys.flags.optimize:
        command.append('-' + 'O' * min(sys.flags.optimize, 2))
    command.extend((str(gate_path), '--root', str(root)))
    return run_checked(command, root)


def audit(root, gate_path, regenerate):
    root = root.resolve(strict=True)
    gate_path = gate_path.resolve(strict=True)
    gate = load_gate(gate_path)
    before, scientific = verify_preimage(root, gate)
    native = native_gate_cli(gate_path, root)
    require(tuple(read(root, p) for p in (ORIGINAL, FREEZE, *ARCHIVES)) == before,
            'preimage changed during verification')
    regenerated = False
    if regenerate:
        # Execute only a pinned generator copied into a disposable directory.
        with tempfile.TemporaryDirectory(prefix='r272_isolated_') as temp:
            sandbox = Path(temp)
            for relative, payload in ((ORIGINAL, before[0]), (FREEZE, before[1])):
                target = sandbox / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(payload)
            run_checked([sys.executable, str(sandbox / ORIGINAL), '--emit'], sandbox)
            native_gate_cli(gate_path, sandbox)
            fresh = tuple(read(sandbox, p) for p in ARCHIVES)
            require(fresh == before[2:], 'isolated regenerated bytes differ from archived preimage')
            regenerated = True
        require(tuple(read(root, p) for p in (ORIGINAL, FREEZE, *ARCHIVES)) == before,
                'archived files changed during isolated regeneration')
    return dict(status='PASS', checked_archived_preimage=True,
                original_receipt_blob=blob(before[4]),
                scientific=scientific, native_checker_stdout=native,
                isolated_regeneration_compared=regenerated,
                original_archives_untouched=True,
                evidence='INTERNAL_NONBLIND_FINITE_ARTIFICIAL_E1')


def self_test(gate_path):
    gate = load_gate(gate_path)
    cb, rb, mb = gate.synthetic_fixture()
    rb = (json.dumps(json.loads(rb), indent=2, ensure_ascii=False) + '\n').encode()
    receipt = json.loads(mb)
    receipt['results_sha256'] = sha(rb)
    mb = (json.dumps(receipt, indent=2) + '\n').encode()
    require(blob(mb) == RECEIPT_BLOB, 'synthetic historical receipt bytes do not match')
    require(gate.verify(cb, rb, mb, pins=True)['status'] == 'PASS', 'positive control')
    # Demonstrate the old candidate's missing receipt byte pin.
    whitespace_changed = mb + b'\n'
    require(gate.verify(cb, rb, whitespace_changed, pins=True)['status'] == 'PASS',
            'expected baseline receipt-byte gap not reproduced')
    require(blob(whitespace_changed) != RECEIPT_BLOB,
            'new byte identity guard failed to detect altered receipt')
    # A scientific mutation with the CSV hash repaired must still be rejected.
    mutated_csv = cb.replace(b'000000,0000,00', b'000001,0000,00', 1)
    require(mutated_csv != cb, 'mutation setup failed')
    altered_receipt = json.loads(mb)
    altered_receipt['source_sha256'] = sha(mutated_csv)
    mutated_receipt = (json.dumps(altered_receipt, indent=2) + '\n').encode()
    rejected = False
    try:
        gate.verify(mutated_csv, rb, mutated_receipt, pins=False)
    except ValueError:
        rejected = True
    require(rejected, 'scientific mutation incorrectly accepted')
    return dict(status='PASS', positive=1,
                original_receipt_blob=blob(mb),
                baseline_receipt_whitespace_accepted=1,
                new_receipt_byte_guard_rejected=1,
                scientific_mutation_rejected=1,
                complete_checkout_native_execution='NOT_RUN')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--root', type=Path)
    parser.add_argument('--gate', type=Path, required=True)
    parser.add_argument('--regenerate', action='store_true')
    parser.add_argument('--self-test', action='store_true')
    args = parser.parse_args()
    require(args.self_test or args.root is not None, 'supply --root or --self-test')
    require(not args.self_test or not args.regenerate, 'self-test cannot regenerate')
    result = self_test(args.gate) if args.self_test else audit(args.root, args.gate, args.regenerate)
    print(json.dumps(result, sort_keys=True))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, RuntimeError, subprocess.TimeoutExpired) as exc:
        raise SystemExit('FAIL: ' + str(exc)) from exc
