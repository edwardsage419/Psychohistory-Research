"use strict";
// Candidate revocation state machine using synthetic devices only. Node.js standard library.
const assert=require("node:assert/strict");
let checks=0;const check=(v,m)=>{checks++;assert.ok(v,m)};
const server={epoch:7,revoked:false,entries:new Map([["derived:1",{epoch:7,payload:"synthetic"}]])};
const a={id:"A",epoch:7,online:true,cache:true,leaseUntil:10,ack:false,lost:false};
const b={id:"B",epoch:7,online:false,cache:true,leaseUntil:10,ack:false,lost:false};
const authorized=(d,now,highImpact)=>d.online ? (!server.revoked&&d.epoch===server.epoch) : (!highImpact&&!d.lost&&now<d.leaseUntil);
check(authorized(b,9,false),"offline cached read before lease expires");
check(!authorized(b,9,true),"offline high impact denied");
server.epoch++;server.revoked=true;server.entries.clear();a.epoch=server.epoch;a.cache=false;a.ack=true;
check(server.epoch===8,"monotone revocation epoch");
check(!authorized(a,9,false),"online revoked read denied");
check(b.cache&&b.epoch===7,"offline physical copy persists");
check(!authorized(b,11,false),"offline lease expiry blocks app read");
const staleUpdate={id:"derived:1",epoch:7,payload:"stale offline edit"};
const mergedCRDT={...staleUpdate};
check(mergedCRDT.payload.length>0,"CRDT-style merge can retain old payload");
const accept=(item)=>!server.revoked&&item.epoch===server.epoch;
check(!accept(staleUpdate),"stale update denied by external policy");
check(server.entries.size===0,"no resurrection in server policy store");
b.lost=true;check(!authorized(b,9,false),"lost device denied by candidate app policy");
check(b.cache,"lost device still physically holds cache");
const globalErasure=()=>!a.cache&&!b.cache&&a.ack&&b.ack?"BACKUPS_UNVERIFIED":"UNVERIFIED";
check(globalErasure()==="UNVERIFIED","missing device acknowledgement");
b.lost=false;b.online=true;
check(!authorized(b,12,false),"stale epoch online denied");
b.epoch=server.epoch;b.cache=false;b.ack=true;
check(globalErasure()==="BACKUPS_UNVERIFIED","backup proof remains open");
check(!accept({id:"derived:1",epoch:7,payload:"late"}),"late old write denied");
check(server.entries.size===0,"no revived derived record");
console.log(JSON.stringify({checks,failures:0,server_epoch:server.epoch,lost_device_before_rejoin:"UNVERIFIED",after_rejoin:globalErasure(),stale_merge_policy:"REJECTED",actual_device_or_backup_deletion:"NOT_TESTED"},null,2));
