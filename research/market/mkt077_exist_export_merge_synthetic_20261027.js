const A=[1,0,1,0],B=[0,1,1,0],C=[1,1,1,0],D=[0,0,0,0];
const union=(a,b)=>a.map((x,i)=>+(!!(x||b[i])));
const u1=union(A,B),u2=union(C,D);
ok(u1.join()===u2.join(),"same union");ok(A.join()!==C.join(),"A differs");
